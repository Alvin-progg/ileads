// Emits the scoring_rules seed migration from lib/scoring/instruments.ts, so
// the rules the tests exercise and the rules the database holds are the same
// values by construction rather than by hand-copying.
//
// Run: node --no-warnings scripts/gen-scoring-rules-sql.mjs > supabase/migrations/<ts>_seed_scoring_rules.sql
//
// Keep --no-warnings and do NOT redirect stderr into the file: Node emits a
// type-stripping warning on stderr that would otherwise land in the SQL and
// break the migration.
import { SEED_RULES } from "../lib/scoring/instruments.ts";

const rows = SEED_RULES.map((r) => {
  // Single-quote escaping for the SQL literal.
  const json = JSON.stringify(r.rules).replaceAll("'", "''");
  return `  ('${r.tool}', ${r.grade_level}, '${r.version}', '${json}'::jsonb)`;
}).join(",\n");

process.stdout.write(`-- Scoring cut-offs (ticket #7).
--
-- Generated by scripts/gen-scoring-rules-sql.mjs from lib/scoring/instruments.ts
-- Do not hand-edit: regenerate instead, so the seeded rules stay identical to
-- the ones the unit tests run against.
--
-- Every number here was transcribed from the Excel formulas in the DepEd
-- workbooks, not from the prose on their Scoring Reference sheets (the two
-- disagree in places).
--
-- RMA grades 1 and 2 carry only what their workbook states: the task letters
-- and the instrument total. Their per-task maxima are null and their level
-- bands empty, so raw scores can be encoded while the proficiency level reads
-- as not yet configured. RMA grades 4-6 are absent entirely - a different
-- domain-based instrument - and the loader raises a clear error for them
-- rather than scoring against a guessed ladder.

insert into scoring_rules (tool, grade_level, version, rules) values
${rows}
on conflict (tool, grade_level, version) do update
  set rules = excluded.rules;
`);
